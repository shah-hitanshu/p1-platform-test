#!/usr/bin/env node
/**
 * Generate `src/sdk-version.ts` from this package's manifest.
 *
 * The SDK reports its own name and version in `x-p1-sdk`, which is how adoption is
 * measured server-side — so a stale value is not a cosmetic problem, it is wrong data
 * attributed to the wrong release.
 *
 * It cannot simply import the manifest: `tsconfig` sets `rootDir: "./src"`, so reaching
 * `../package.json` puts a file outside the root and rewrites the published layout to
 * `dist/src/**`, breaking every path in `exports`. Generating a tiny module instead
 * keeps the manifest out of the build and the value out of anyone's hands.
 *
 * Runs from `prebuild`, so a publish always embeds the version being published, and
 * from the repo's `ci:version`, so a `changeset version` bump updates it in the same
 * commit rather than leaving the next CI run to discover the drift.
 *
 * `--check` verifies without writing, for use as a guard.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const manifestPath = new URL('../package.json', import.meta.url);
const targetPath = new URL('../src/sdk-version.ts', import.meta.url);

const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'));
const scopedName = manifest.name;
const bareName = scopedName.replace(/^@[^/]+\//, '');

const contents = `/**
 * Generated by \`scripts/sync-sdk-version.mjs\` from package.json. Do not edit.
 *
 * Run \`pnpm --filter ${scopedName} sync-version\` to regenerate; \`prebuild\` and the
 * repo's \`ci:version\` do it automatically.
 */

/** Name half of \`x-p1-sdk\`. */
export const SDK_NAME = '${bareName}';

/** Version half of \`x-p1-sdk\`, matching the published release. */
export const SDK_VERSION = '${manifest.version}';
`;

const current = (() => {
  try {
    return readFileSync(targetPath, 'utf8');
  } catch {
    return null;
  }
})();

if (current === contents) process.exit(0);

if (process.argv.includes('--check')) {
  process.stderr.write(
    `sdk-version.ts is out of sync with package.json (${manifest.version}).\n` +
      `Run: pnpm --filter ${scopedName} sync-version\n`,
  );
  process.exit(1);
}

writeFileSync(targetPath, contents);
process.stdout.write(`[sync-sdk-version] ${fileURLToPath(targetPath)} -> ${manifest.version}\n`);
