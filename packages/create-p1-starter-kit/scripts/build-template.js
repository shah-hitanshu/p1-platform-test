import fs from 'fs';
import path from 'path';
import { execFileSync } from 'child_process';
import { fileURLToPath } from 'url';
import { indexWorkspacePackages, resolveWorkspaceDeps } from './workspace-deps.js';
import {
  readPresetImports,
  collectPresets,
  inlinePresets,
  validateConfig,
} from './eslint-inline.js';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const repoRoot = path.resolve(__dirname, '../../..');
const templateSource = path.join(repoRoot, 'apps/p1-starter');
const templateDest = path.join(__dirname, '../template');
// Files authored for scaffold consumers, overlaid on top of the copied app.
const assetsDir = path.join(__dirname, '../template-assets');

// npm strips any file named `.gitignore` from a published tarball, so the
// template carries it undotted and copy-template.js restores the name on scaffold.
const GITIGNORE_TEMPLATE_NAME = 'gitignore';

// Directories and files to skip when copying
const SKIP_PATTERNS = new Set([
  'node_modules',
  '.next',
  'dist',
  '.turbo',
  '.env.local',
  '.env',
  'coverage',
  'test-results',
  'playwright-report',
  '.DS_Store',
  // Both are monorepo artifacts: the README describes the sample app in this
  // repo, and the CHANGELOG is changesets' record of internal releases.
  // template-assets/README.md replaces the former; nothing replaces the latter.
  'README.md',
  'CHANGELOG.md',
  // Generated by `next dev` / `next build` on first run. The copy here resolves
  // `.next/types/routes.d.ts`, which a freshly scaffolded project has not built
  // yet; dropping it leaves typecheck output unchanged.
  'next-env.d.ts',
]);

// Tests that only make sense inside this repo. Everything else in the app's
// suite runs verbatim against the published packages a scaffold installs.
const MONOREPO_ONLY_TESTS = new Set([
  // Asserts the monorepo README against apps/p1-starter. The scaffold ships a
  // different README, covered by this package's own build-template.test.js.
  'readme-accuracy.test.ts',
]);

// Skip rules whose target the app always has, so a rule that matches nothing
// means the app renamed or deleted the file it was written for — and the template
// is now shipping something the build meant to withhold. That is how a monorepo
// README and a 466KB tsbuildinfo reached customers. The rest of the skip list is
// best-effort: developer-local files (.env) and build output (.next, dist) are
// absent on a clean checkout, so their absence proves nothing.
export const RULES_THAT_MUST_MATCH = new Set([
  'node_modules',
  'README.md',
  'CHANGELOG.md',
  ...MONOREPO_ONLY_TESTS,
]);

const matchedRules = new Set();

function shouldSkip(name) {
  // A .tsbuildinfo is an incremental-build cache keyed to absolute paths inside
  // this monorepo's node_modules — meaningless to a customer, and stale by the
  // time it reaches them. Matched by suffix: the name follows the tsconfig.
  if (SKIP_PATTERNS.has(name) || MONOREPO_ONLY_TESTS.has(name)) {
    matchedRules.add(name);
    return true;
  }
  return name.endsWith('.tsbuildinfo');
}

export function findDeadRules(matched) {
  return [...RULES_THAT_MUST_MATCH].filter((rule) => !matched.has(rule));
}

function assertNoDeadRules() {
  const dead = findDeadRules(matchedRules);

  if (dead.length > 0) {
    throw new Error(
      `These skip rules matched nothing under ${templateSource}: ${dead.join(', ')}. ` +
      'The app renamed or removed the files they were written for, so the template ' +
      'is now shipping something the build meant to withhold. Update the rule.'
    );
  }
}

function copyRecursive(src, dest, rootDest) {
  if (!rootDest) {
    rootDest = path.resolve(dest);
  }

  const resolvedDest = path.resolve(dest);
  if (!resolvedDest.startsWith(rootDest)) {
    throw new Error(`Path traversal detected: ${dest} is outside target directory`);
  }

  if (!fs.existsSync(dest)) {
    fs.mkdirSync(dest, { recursive: true });
  }

  const entries = fs.readdirSync(src, { withFileTypes: true });

  for (const entry of entries) {
    if (shouldSkip(entry.name)) {
      continue;
    }

    const srcPath = path.join(src, entry.name);
    const destPath = path.join(dest, entry.name);

    const resolvedDestPath = path.resolve(destPath);
    if (!resolvedDestPath.startsWith(rootDest)) {
      throw new Error(`Path traversal detected: ${entry.name} attempts to escape target directory`);
    }

    if (entry.isDirectory()) {
      copyRecursive(srcPath, destPath, rootDest);
    } else {
      fs.copyFileSync(srcPath, destPath);
    }
  }
}

function transformPackageJson(destPath) {
  const pkgPath = path.join(destPath, 'package.json');
  let pkg;

  try {
    pkg = JSON.parse(fs.readFileSync(pkgPath, 'utf-8'));
  } catch (error) {
    throw new Error(`Failed to parse package.json: ${error.message}`);
  }

  pkg.name = 'PLACEHOLDER_PROJECT_NAME';
  // Monorepo-internal script (run via the repo root's dev:stack); not for scaffolded apps.
  delete pkg.scripts['dev:stack'];
  pkg.version = '0.1.0';
  delete pkg.private;

  // Must precede resolveWorkspaceDeps: eslint-config is private, so leaving it in
  // place would abort the build instead of inlining its dependencies.
  if (pkg.devDependencies) {
    delete pkg.devDependencies['@pantheon-systems/eslint-config'];
    const eslintConfigPkg = JSON.parse(
      fs.readFileSync(path.join(repoRoot, 'packages/eslint-config/package.json'), 'utf-8')
    );
    Object.assign(pkg.devDependencies, eslintConfigPkg.dependencies);
    console.log('  Replaced @pantheon-systems/eslint-config with standalone eslint deps');
  }

  resolveWorkspaceDeps(pkg, indexWorkspacePackages(path.join(repoRoot, 'packages')), console.log);

  fs.writeFileSync(pkgPath, JSON.stringify(pkg, null, 2) + '\n');
}

function rewriteEslintConfig(destPath) {
  const configPath = path.join(destPath, 'eslint.config.js');
  const eslintConfigDir = path.join(repoRoot, 'packages/eslint-config');

  const presetNames = readPresetImports(fs.readFileSync(configPath, 'utf-8'));
  if (presetNames.length === 0) {
    throw new Error(
      `${configPath} imports no @pantheon-systems/eslint-config presets. ` +
      'The app config format changed; update readPresetImports().'
    );
  }

  const presets = collectPresets(presetNames, (name) =>
    fs.readFileSync(path.join(eslintConfigDir, `${name}.js`), 'utf-8')
  );

  const config = validateConfig(inlinePresets(presets), presetNames);
  fs.writeFileSync(configPath, config);

  // The scaffold's config is only exercised when a customer runs lint, so parse
  // it here rather than shipping a file that throws on their first `npm run lint`.
  execFileSync(process.execPath, ['--check', configPath]);

  console.log(`  Rewrote eslint.config.js, inlining: ${presets.map((p) => p.name).join(', ')}`);
}

function stageGitignore(destPath) {
  const dotted = path.join(destPath, '.gitignore');
  if (!fs.existsSync(dotted)) {
    throw new Error(
      `${templateSource}/.gitignore is missing, so scaffolds would commit node_modules ` +
      'on their initial commit.'
    );
  }
  fs.renameSync(dotted, path.join(destPath, GITIGNORE_TEMPLATE_NAME));
  console.log(`  Renamed .gitignore → ${GITIGNORE_TEMPLATE_NAME} (npm strips dotted gitignores)`);
}

function copyAssets(destPath) {
  for (const entry of fs.readdirSync(assetsDir)) {
    // Recursive: the directory is flat today, but a nested asset should overlay
    // rather than abort the build with a bare EISDIR.
    fs.cpSync(path.join(assetsDir, entry), path.join(destPath, entry), { recursive: true });
    console.log(`  Added ${entry} from template-assets/`);
  }
}

export function buildTemplate(destPath = templateDest) {
  if (!fs.existsSync(templateSource)) {
    throw new Error(`Template source not found at ${templateSource}`);
  }

  if (fs.existsSync(destPath)) {
    console.log('Removing existing template directory...');
    fs.rmSync(destPath, { recursive: true });
  }

  console.log('Copying template files...');
  matchedRules.clear();
  copyRecursive(templateSource, destPath);
  assertNoDeadRules();

  console.log('Transforming package.json...');
  transformPackageJson(destPath);

  console.log('Rewriting eslint config...');
  rewriteEslintConfig(destPath);

  console.log('Staging .gitignore for publication...');
  stageGitignore(destPath);

  console.log('Adding scaffold-authored files...');
  copyAssets(destPath);

  console.log('Generating pnpm-workspace.yaml...');
  const workspaceYaml = fs.readFileSync(path.join(repoRoot, 'pnpm-workspace.yaml'), 'utf-8');
  const allowBuildsMatch = workspaceYaml.match(/allowBuilds:\n((?:\s+\S+:\s+true\n?)+)/);
  if (allowBuildsMatch) {
    fs.writeFileSync(
      path.join(destPath, 'pnpm-workspace.yaml'),
      `allowBuilds:\n${allowBuildsMatch[1]}`
    );
    const pkgs = [...allowBuildsMatch[1].matchAll(/\s+(\S+):\s+true/g)].map((m) => m[1]);
    console.log(`  allowBuilds: ${pkgs.join(', ')}`);
  }

  return destPath;
}

if (process.argv[1] && path.resolve(process.argv[1]) === __filename) {
  console.log('Building template from apps/p1-starter...');
  try {
    buildTemplate();
  } catch (error) {
    console.error(`Error: ${error.message}`);
    process.exit(1);
  }
  console.log('✓ Template built successfully from apps/p1-starter');
}
